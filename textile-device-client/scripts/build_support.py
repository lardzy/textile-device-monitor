class BuildValidationError(RuntimeError):
    pass


def _distribution_version(name: str) -> str:
    try:
        return metadata.version(name)
    except metadata.PackageNotFoundError:
        # Real builds call ensure_build_environment() first. This fallback keeps
        # manifest helpers usable for isolated unit tests and diagnostics.
        return "not-installed"


def read_app_version(project_root: Path) -> str:
    version_file = project_root / "modules" / "version.py"
    payload = version_file.read_text(encoding="utf-8")
    match = _VERSION_PATTERN.search(payload)
    if match is None:
        raise RuntimeError(f"Unable to parse app version from {version_file}")
    return match.group(1).strip()


def write_installer_version_include(project_root: Path) -> Path:
    version = read_app_version(project_root)
    output = project_root / "packaging" / "inno-setup" / "version.auto.iss"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        (
            "; Auto-generated by scripts/build_support.py / build scripts\n"
            f'#define MyAppVersion "{version}"\n'
        ),
        encoding="utf-8",
    )
    return output


def _windows_version_tuple(version: str) -> tuple[int, int, int, int]:
    parts = version.split(".")
    if not 1 <= len(parts) <= 4 or any(not part.isdigit() for part in parts):
        raise BuildValidationError(
            f"App version must contain 1-4 numeric components: {version!r}"
        )
    values = [int(part) for part in parts]
    if any(value > 65535 for value in values):
        raise BuildValidationError(
            f"App version components must be <= 65535: {version!r}"
        )
    return tuple((values + [0, 0, 0, 0])[:4])


